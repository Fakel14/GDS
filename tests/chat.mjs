import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {spawn,spawnSync} from 'node:child_process';
import {once} from 'node:events';
import assert from 'node:assert/strict';
const dir=mkdtempSync(join(tmpdir(),'gds-chat-')),env={...process.env,GDS_DATA_DIR:dir,PORT:'31993'};
const run=(...args)=>spawnSync(process.execPath,['server/admin.js',...args],{env,encoding:'utf8'});
const create=(n)=>{const r=run('create',n);assert.equal(r.status,0,r.stderr);return {id:r.stdout.match(/ID: (.+)/)[1],code:r.stdout.match(/Код: (.+)/)[1]}};
const admin=create('Fakelo4ik'),seller=create('Seller'),buyer=create('Buyer'),other=create('Other');assert.equal(run('grant-admin',admin.id).status,0);
const server=spawn(process.execPath,['server/index.js'],{env,stdio:['ignore','pipe','inherit']});
try{await once(server.stdout,'data');const base='http://localhost:31993';
 const req=async(path,method='GET',data,cookie='')=>{const r=await fetch(base+path,{method,headers:{origin:base,'content-type':'application/json',cookie},body:data===undefined?undefined:JSON.stringify(data)});return {status:r.status,data:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]}};
 const login=async(a)=>{const r=await req('/api/login','POST',a);assert.equal(r.status,200);return r.cookie};const ac=await login(admin),sc=await login(seller),bc=await login(buyer),oc=await login(other);
 const sr=await req('/api/seller-request','POST',{},sc);assert.equal(sr.status,200);assert.equal(run('approve-seller',seller.id,sr.data.requestCode).status,0);
 const fields={title:'Трек',category:'Оригинальный трек',price:123,description:'Описание',comment:'скрыто',paymentMethod:'СБП',paymentDetails:'123' };
 let l=(await req('/api/listings','POST',fields,sc)).data.listing;
 assert.equal((await req('/api/conversations','POST',{listingId:l.id},bc)).status,404);
 await req('/api/listings/'+l.id+'/approve','POST',{},ac);
 assert.equal((await req('/api/conversations','POST',{listingId:l.id},sc)).status,400);
 assert.equal((await req('/api/conversations','POST',{listingId:l.id})).status,401);
 let c=(await req('/api/conversations','POST',{listingId:l.id},bc)).data.conversation;
 assert.equal((await req('/api/conversations','POST',{listingId:l.id},bc)).data.conversation.id,c.id);
 assert.equal((await req('/api/conversations/'+c.id,'GET',undefined,oc)).status,403);
 assert.equal((await req('/api/conversations?scope=all','GET',undefined,oc)).data.conversations.length,0);
 assert.equal((await req('/api/conversations?scope=all','GET',undefined,ac)).data.conversations.length,1);
 assert.equal((await req('/api/conversations/'+c.id+'/messages','POST',{text:'Вмешательство'},ac)).status,403);
 assert.equal((await req('/api/conversations/'+c.id+'/messages','POST',{text:'   '},bc)).status,400);
 assert.equal((await req('/api/conversations/'+c.id+'/messages','POST',{text:'Привет <script>тест</script>'},bc)).status,201);
 assert.equal((await req('/api/conversations/'+c.id+'/messages','POST',{text:'Привет!'},sc)).status,201);
 assert.equal((await req('/api/conversations/'+c.id,'GET',undefined,ac)).data.conversation.messages.length,2);
 assert.equal((await req('/api/profiles/Seller/ban','POST',{},oc)).status,403);
 assert.equal((await req('/api/profiles/Seller/ban','POST',{},ac)).status,200);
 assert.equal((await req('/api/session','GET',undefined,sc)).data.user,null);
 assert.equal((await req('/api/login','POST',seller)).status,403);
 assert.equal((await req('/api/listings')).data.listings.length,0);
 assert.equal((await req('/api/conversations/'+c.id+'/messages','POST',{text:'ещё'},bc)).status,409);
 assert.equal((await req('/api/profiles/Seller/unban','POST',{},ac)).status,200);
 assert.equal((await req('/api/listings')).data.listings.length,1);
 assert.equal((await req('/api/profiles/Seller','DELETE',{},ac)).status,200);
 const history=(await req('/api/conversations/'+c.id,'GET',undefined,bc)).data.conversation;
 assert.equal(history.seller,'Удалённый аккаунт');assert.equal(history.messages.length,2);assert.equal(history.canSend,false);
 console.log('Chat access, moderation, persistence and bans passed');
}finally{server.kill();rmSync(dir,{recursive:true,force:true})}
